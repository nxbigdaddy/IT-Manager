"""Backend boundary. SQLite is the only implemented backend in release one."""
import os
from pathlib import Path
from typing import Any, Mapping, Protocol, runtime_checkable


@runtime_checkable
class Repository(Protocol):
    def list_records(self, module=None, include_archived=False) -> list[dict]: ...
    def get_record(self, oid) -> dict | None: ...
    def page_records(self, module=None, query='', owner='', status='', start='', end='',
                     limit=100, offset=0, include_archived=False) -> dict: ...
    def save_record(self, module, data, oid=None, version=None) -> dict: ...
    def archive_record(self, oid, version) -> dict: ...
    def batch_update_records(self, updates, request_id) -> dict: ...
    def batch_archive_records(self, targets, request_id) -> dict: ...
    def task_action(self, oid, version, action, payload, request_id) -> dict: ...
    def create_actions(self, source_id, items, request_id) -> dict: ...
    def complete_checklist(self, data, request_id) -> dict: ...
    def apply_workspace_bundle(self, workspace_data, records, request_id) -> dict: ...
    def record_history(self, oid) -> list[dict]: ...
    def import_preview(self, records) -> dict: ...
    def import_records(self, records) -> dict: ...
    def objects(self, kind) -> list[dict]: ...
    def get(self, kind, oid) -> dict | None: ...
    def put(self, kind, data, oid=None) -> dict: ...
    def delete_object(self, kind, oid) -> dict: ...
    def save_versioned_object(self, kind, data, oid=None, expected_version=None, *, prompt_defaults=False) -> dict: ...
    def review_draft(self, oid, expected_revision, content, approved) -> dict: ...
    def claim_approved_delivery(self, draft_id, channel_id, request_id, expected_revision) -> dict | None: ...
    def claim_delivery(self, schedule_id, slot, data) -> str | None: ...
    def delivery_state(self, oid, state, detail) -> None: ...
    def deliveries(self) -> list[dict]: ...
    def record_audit(self, action, oid, detail='') -> None: ...
    def audit_rows(self) -> list[dict]: ...
    def backup(self, folder) -> str: ...
    def validate_backup(self, path) -> dict: ...


def create_repository(config: Mapping[str, Any] | None = None, *, backend=None, path=None) -> Repository:
    """Explicit args override config, then ITMANAGER_DB_BACKEND/DB_PATH.

    config is {'backend': 'sqlite', 'path': '/local/path.sqlite3'}.
    No silent fallback to SQLite for a misconfigured server backend.
    """
    from .store import Store
    config = {} if config is None else config
    if not isinstance(config, Mapping):
        raise ValueError('数据库配置必须为映射')
    selected = backend if backend is not None else config.get('backend', os.environ.get('ITMANAGER_DB_BACKEND', 'sqlite'))
    if not isinstance(selected, str):
        raise ValueError('数据库backend必须为文本')
    selected = selected.lower().strip()
    if selected in {'postgres', 'postgresql', 'mysql'}:
        raise ValueError(selected + ' backend尚未实现；首版仅支持SQLite')
    if selected != 'sqlite':
        raise ValueError('不支持的数据库backend: ' + selected)
    location = path if path is not None else config.get('path', os.environ.get('ITMANAGER_DB_PATH'))
    if not isinstance(location, (str, Path)) or not str(location).strip():
        raise ValueError('SQLite需要本地数据库path配置')
    return Store(location)


repository_factory = create_repository
