def sheet(name, headers, rows=(), dropdowns=None):
    ws=wb.create_sheet(name); ws.append(headers)
    for r in rows: ws.append(r)
    ws.freeze_panes='B2'; ws.auto_filter.ref=f'A1:{ws.cell(1,len(headers)).column_letter}501'
    ws.row_dimensions[1].height=34
    for c in ws[1]:
        c.fill=PatternFill('solid',fgColor=navy); c.font=Font(name='微软雅黑',color='FFFFFF',bold=True); c.alignment=Alignment(wrap_text=True,vertical='center')
    for row in ws.iter_rows(min_row=2,max_row=max(ws.max_row,16),max_col=len(headers)):
        for c in row:
            c.font=Font(name='微软雅黑',size=10); c.alignment=Alignment(vertical='top',wrap_text=True)
            if c.row%2==0:c.fill=PatternFill('solid',fgColor='F2F6FA')
        ws.row_dimensions[row[0].row].height=48
    for i,h in enumerate(headers,1):
        col=ws.cell(1,i).column_letter
        ws.column_dimensions[col].width=16 if ('ID' in h or '日期' in h or '时间' in h or h in ['状态','负责人','优先级']) else 27
        if any(x in h for x in ['内容','证据','标准','措施','描述','下一步','支撑','方法','口径']):ws.column_dimensions[col].width=42
        if any(x in h for x in ['日期','截止日','到期日','复核日']) and '目标' not in h:
            for rr in range(2,502):ws.cell(rr,i).number_format='yyyy-mm-dd'
        if '金额' in h or '预算(元)' in h or '费用(元)' in h:
            for rr in range(2,502):ws.cell(rr,i).number_format='#,##0.00'
    for h,opts in (dropdowns or {}).items():
        i=headers.index(h)+1; col=ws.cell(1,i).column_letter
        dv=DataValidation(type='list',formula1='"'+','.join(opts)+'"',allow_blank=True)
        dv.errorTitle='请选择列表值';dv.error='请使用下拉中的标准值。';dv.showErrorMessage=True
        ws.add_data_validation(dv);dv.add(f'{col}2:{col}501')
    return ws
